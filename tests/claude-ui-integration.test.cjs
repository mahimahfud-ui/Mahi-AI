const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const html = read("public/index.html");
const css = read("public/mahi.css");
const adapter = read("public/ui-adapter.js");
const app = read("public/app.js");
const voice = read("public/live-voice.js");
const admin = read("public/admin-control.js");
const codeBlocks = read("public/code-blocks.js");

test("the production HTML uses the supplied welcome design without demo-reply copy", () => {
  assert.match(html, /Quiet space for clear thinking\./);
  assert.match(html, /Write a JavaScript debounce function/);
  assert.match(html, /Draft a project update email/);
  assert.match(html, /Explain how tides work/);
  assert.match(html, /Plan a focused week/);
  const welcome = html.slice(html.indexOf('<section class="welcome" id="welcome">'), html.indexOf('<section class="messages" id="messages"'));
  assert.doesNotMatch(welcome, /frontend demo|local samples|not generated by an AI model/i);
  assert.match(html, /class="topbar-title-text"[^>]*>MahiCloud/);
});

test("all required production IDs remain unique", () => {
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
  assert.equal(ids.length, new Set(ids).size, "HTML must not contain duplicate IDs");
  for (const id of [
    "newChat", "chatList", "chatSearch", "chatForm", "promptInput", "sendButton", "stopButton",
    "modelPicker", "thinkModeButton", "fileInput", "attachmentList", "accountModal",
    "accountEmailInput", "accountPhoneInput", "accountOtpInput", "themeToggle", "quickThemeToggle",
    "voiceOverlay", "voiceMicButton", "adminControlOverlay", "adminLoginForm", "adminSave",
    "exportMarkdownButton", "exportJsonButton", "apiExplorer"
  ]) {
    assert.ok(ids.includes(id), "missing production hook: " + id);
  }
});

test("the live production scripts and styles remain wired in safe order", () => {
  for (const asset of [
    "./styles.css", "./theme.css", "./motion.css", "./craft.css", "./motion-b.css",
    "./ui-overrides.css", "./code-blocks.css", "./admin-control.css", "./mahi.css"
  ]) assert.ok(html.includes(asset), "missing stylesheet: " + asset);
  for (const asset of ["./config.js", "./themes.js", "./app.js", "./live-voice.js", "./admin-control.js", "./code-blocks.js", "./ui-adapter.js"]) {
    assert.ok(html.includes(asset), "missing script: " + asset);
  }
  assert.ok(html.indexOf("./mahi.css?v=claude-ui-20261029") > html.indexOf("./admin-control.css"));
  assert.ok(html.indexOf("./ui-adapter.js?v=20261029") > html.indexOf("./app.js"));
  assert.doesNotMatch(html, /js\/app\.js|mahicloud\.part1|data-form="admin"/);
});

test("chat, streaming, history, think mode and attachments still use production contracts", () => {
  for (const contract of [
    '"/functions/v1/mahi-ai-chat"',
    'conversation_id: temporaryChatMode ? null : conversationId',
    'temporary_chat: temporaryChatMode',
    'think_mode: useThinkMode && selectedModel === "auto"',
    'selected_model: selectedModel === "auto" ? "" : selectedModel',
    'payload.type === "delta"',
    'payload.type === "done"',
    'from("mahi_ai_conversations")',
    'from("mahi_ai_messages")',
    'from("mahi-ai-attachments")',
    'async function uploadPendingAttachments'
  ]) assert.ok(app.includes(contract), "missing chat/backend contract: " + contract);
  assert.match(app, /new AbortController\(\)/);
});

test("account, voice, code-block and protected admin integrations remain production implementations", () => {
  assert.match(app, /client\.auth\.signInWithPassword/);
  assert.match(app, /client\.auth\.signInWithOtp/);
  assert.match(app, /client\.auth\.verifyOtp/);
  assert.match(app, /MahiCloudRequestLiveVoiceToken/);
  assert.match(app, /functions\/v1\/mahi-ai-live-token/);
  assert.match(voice, /MahiCloudRequestLiveVoiceToken/);
  assert.match(admin, /functions\/v1\/mahi-ai-chat/);
  assert.match(codeBlocks, /sandbox/);
  assert.match(adapter, /existingThemeToggle\.click\(\)/);
  assert.doesNotThrow(() => new vm.Script(adapter), "theme adapter must parse as browser JavaScript");
  assert.match(adapter, /MutationObserver/);
  assert.match(adapter, /\.chat-item\.active \.chat-title/);
});

test("the presentation layer stays responsive and respects accessibility preferences", () => {
  assert.match(css, /@media\s*\(max-width:\s*600px\)/);
  assert.match(css, /@media\s*\(max-width:\s*360px\)/);
  assert.match(css, /@media\s*\(prefers-reduced-motion:\s*reduce\)/);
  assert.match(css, /:focus-visible/);
  assert.match(css, /\.suggestion-grid[\s\S]*grid-template-columns/);
  assert.match(css, /\.quick-theme-button/);
});
