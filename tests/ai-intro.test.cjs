const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");

const html = fs.readFileSync(require.resolve("../public/index.html"), "utf8");

test("the current MahiCloud page opens directly into the real chat shell", () => {
  assert.match(html, /<title>MahiCloud<\/title>/);
  assert.match(html, /id="app"/);
  assert.match(html, /id="welcome"/);
  assert.match(html, /id="composer"/);
  assert.match(html, /id="msgs"/);
  assert.doesNotMatch(html, /id="aiIntro"|ai-intro\.css|ai-intro\.js/);
});

test("the initial welcome screen is real product UI, not a demo or fake response", () => {
  assert.match(html, /MahiCloud/);
  assert.match(html, /Message MahiCloud/);
  assert.match(html, /id="newChat"/);
  assert.match(html, /id="send"/);
  assert.doesNotMatch(html, /frontend demo|local samples|not generated by an AI model/i);
});

test("the page bootstraps its actual app session without a blocking intro timer", () => {
  assert.match(html, /async function boot|function boot/);
  assert.match(html, /await Api\.ensure\(\)/);
  assert.doesNotMatch(html, /setTimeout\(finishIntro/);
});
